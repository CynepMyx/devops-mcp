@pytest.mark.parametrize("cmd", NEEDS_CONFIRMATION)
def test_needs_confirmation(cmd):
    with pytest.raises((ValueError, PermissionError)):
        validate_ssh_command(cmd, confirmed=False)
    assert not is_read_only_command(cmd)  # and is never retried after a dropped connection


@pytest.mark.parametrize("cmd", READS)
def test_reads_pass(cmd):
    validate_ssh_command(cmd, confirmed=False)


@pytest.mark.parametrize("cmd", [
    'echo done sleep 300; pkill -f "[s]leep 300"',
    'pgrep -f "[r]un-all" && echo run-all',
])
def test_bracket_pattern_repeated_in_the_command_is_refused(cmd):
    with pytest.raises(PermissionError, match="also appears"):
        validate_ssh_command(cmd, confirmed=True)


@pytest.mark.parametrize("cmd", ['pkill -f "[s]leep 300"', 'pgrep -f "[r]un-all"'])
def test_bracket_pattern_alone_still_works(cmd):
    validate_ssh_command(cmd, confirmed=True)
